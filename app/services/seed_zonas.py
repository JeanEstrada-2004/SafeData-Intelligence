def _extract_zone_id(feature: dict) -> Optional[int]:
    for key in feature.get("properties", {}).keys():
        if isinstance(key, str) and key.lower().startswith("zona"):
            try:
                return int(key.lower().replace("zona", "").strip())
            except ValueError:
                continue
    return None


def _compute_centroid(coordinates: List[List[List[float]]]) -> tuple[float, float]:
    ring = coordinates[0]
    if len(ring) > 1 and ring[0] == ring[-1]:
        ring = ring[:-1]

    if not ring:
        return CENTER_LAT, CENTER_LON

    total_lon = 0.0
    total_lat = 0.0
    for lon, lat in ring:
        total_lon += lon
        total_lat += lat

    return total_lat / len(ring), total_lon / len(ring)


def build_test_zones() -> List[Zona]:
    """Construye las 7 zonas usando el GeoJSON real del proyecto."""
    zones = []
    for feature in ZONES_GEOJSON["features"]:
        zone_id = _extract_zone_id(feature) or len(zones) + 1
        centroid_lat, centroid_lon = _compute_centroid(feature["geometry"]["coordinates"])
        zones.append(
            Zona(
                id_zona=zone_id,
                nombre=f"Z{zone_id}",
                geojson={"type": "Feature", "geometry": feature["geometry"], "properties": {"id": zone_id, "name": f"Z{zone_id}"}},
                centroid_lat=centroid_lat,
                centroid_lon=centroid_lon,
            )
        )
    return zones


def upsert_zones(session: Session) -> int:
    existing_ids = set(session.scalars(select(Zona.id_zona)).all())
    items = build_test_zones()
    inserted = 0
    for item in items:
        if item.id_zona in existing_ids:
            # update simple (nombre/geojson/centroides)
            db_item = session.get(Zona, item.id_zona)
            db_item.nombre = item.nombre
            db_item.geojson = item.geojson
            db_item.centroid_lat = item.centroid_lat
            db_item.centroid_lon = item.centroid_lon
        else:
            session.add(item)
            inserted += 1
    session.commit()
    return inserted


def main() -> None:
    session = SessionLocal()
    try:
        n = upsert_zones(session)
        print(f"Zonas listas. Insertadas: {n} (otras fueron actualizadas si existían).")
    finally:
        session.close()


if __name__ == "__main__":
    main()
